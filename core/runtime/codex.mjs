/** Fixed native Codex authorization owner. No remote auth or credential payload projection. */
import { validateCodexRuntimeValues, projectCodexRuntimeValues, projectCodexRuntimeBaseValues, codexRuntimePathOps,
  validCodexRuntimeRevision, runtimeUnavailable } from './codex-runtime-values.mjs';
const KEY = 'llm-pi-ai/openai-codex';
const PROVIDER = 'openai-codex';
const safeId = value => Number.isSafeInteger(value) && value > 0;
const object = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const get = (ctx, name) => ctx.get(name);
// Cordis returns fresh context-bound proxies; its original symbol identifies the service instance.
const ORIGINAL = Symbol.for('cordis.original');
const sameService = (left, right) => !!left && !!right && (left[ORIGINAL] ?? left) === (right[ORIGINAL] ?? right);
const at = (value, path) => path.reduce((v, key) => object(v) && Object.hasOwn(v, key) ? v[key] : undefined, value);
const validPath = path => Array.isArray(path) && path.length === 2 && path[0] === 'providers' && path[1] === PROVIDER;
const exact = (value, keys) => object(value) && Object.keys(value).sort().join(',') === [...keys].sort().join(',');
export const validCodexAccountId = value => typeof value === 'string' && /^account-[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(value);
export const validCodexLabel = value => typeof value === 'string' && value.trim().length > 0 && [...value].length >= 1 && [...value].length <= 128 && Buffer.byteLength(value) <= 512 && !/[\p{Cc}\p{Cs}\p{Cf}\p{Zl}\p{Zp}]/u.test(value);
const validEpoch = value => Number.isSafeInteger(value) && value >= 0;
const MAX_ACCOUNT_METADATA_BYTES = 61_440;
const boundedAccounts = value => {
  if (Buffer.byteLength(JSON.stringify(value)) > MAX_ACCOUNT_METADATA_BYTES) throw unavailable();
  return value;
};
const unavailable = () => new Error('Codex unavailable');
const conflict = () => Object.assign(unavailable(), { code: 'CODEX_EPOCH_CONFLICT' });
const accountMetadata = value => {
  if (!exact(value, ['opaqueId', 'label', 'email', 'plan']) || !validCodexAccountId(value.opaqueId) || !validCodexLabel(value.label) || value.email !== null || value.plan !== null) throw unavailable();
  return { opaqueId: value.opaqueId, label: value.label, email: null, plan: null };
};
/** Validate Host-owned public metadata before crossing the private pipe. No grants are read. */
export function codexAccountsMetadata(value) {
  if (!exact(value, ['accounts', 'selected', 'epoch', 'legacy']) || !Array.isArray(value.accounts) || value.accounts.length > 128 || !validEpoch(value.epoch) || !['unadopted', 'absent'].includes(value.legacy)) throw unavailable();
  const accounts = value.accounts.map(accountMetadata);
  if (new Set(accounts.map(row => row.opaqueId)).size !== accounts.length || value.selected !== null && !accounts.some(row => row.opaqueId === value.selected)) throw unavailable();
  return boundedAccounts({ accounts, selected: value.selected, epoch: value.epoch, legacy: value.legacy });
}

/** Validate the exact URL generated by the installed pi-ai browser flow. */
export function validCodexUrl(raw) {
  if (typeof raw !== 'string' || raw.length > 16384 || /[\x00-\x20\x7f]/.test(raw)) return false;
  let url;
  try { url = new URL(raw); } catch (_error) { return false; }
  if (url.origin !== 'https://auth.openai.com' || url.pathname !== '/oauth/authorize' || url.username || url.password || url.hash) return false;
  const expected = { response_type: 'code', client_id: 'app_EMoamEEZ73f0CkXaXp7hrann', redirect_uri: 'http://localhost:1455/auth/callback', scope: 'openid profile email offline_access', code_challenge_method: 'S256', id_token_add_organizations: 'true', codex_cli_simplified_flow: 'true', originator: 'pi' };
  const keys = [...Object.keys(expected), 'state', 'code_challenge'];
  if ([...url.searchParams].length !== keys.length || keys.some(key => url.searchParams.getAll(key).length !== 1)) return false;
  return Object.entries(expected).every(([key, value]) => url.searchParams.get(key) === value)
    && /^[a-f0-9]{32}$/.test(url.searchParams.get('state') ?? '')
    && /^[A-Za-z0-9_-]{43}$/.test(url.searchParams.get('code_challenge') ?? '');
}

/** The owner retains prompt resolvers and secrets only for its one local attempt. */
export function createCodexBridge({ ctx, emit, addSecret = () => {}, timeoutMs = 15 * 60 * 1000 }) {
  let next = 0;
  let active = null;
  let stopped = false;
  let stopTask = null;
  let retryBlocked = false;
  let phase = 'idle';
  let version = 0;
  let managedSeen = false;
  let added = null;
  let mutationTail = Promise.resolve();
  let mutations = 0;
  const cancelTasks = new Set();
  const managed = () => {
    const found = get(ctx, 'codexAccounts');
    if (found) managedSeen = true;
    if (managedSeen && !found) throw unavailable();
    return found ?? null;
  };
  const currentOwner = owner => {
    const current = managed();
    if (!sameService(current, owner)) throw unavailable();
    return current;
  };
  const readAccounts = async owner => {
    const value = codexAccountsMetadata(await currentOwner(owner).describe());
    if (stopped) throw unavailable();
    currentOwner(owner);
    return value;
  };
  const accountsStatus = async (reconcile = false) => {
    const owner = managed();
    if (!owner) return { mode: 'legacy', accounts: [], selected: null, epoch: null, legacy: 'absent', added: null };
    if (reconcile && (active?.running || mutations > 0)) throw unavailable();
    const state = await readAccounts(owner);
    if (reconcile && (active?.running || mutations > 0)) throw unavailable();
    if (reconcile) {
      retryBlocked = false;
      if (phase === 'indeterminate' || phase === 'failed' || phase === 'cancelled') { phase = 'idle'; active = null; }
      version++;
    }
    const receipt = added && state.accounts.some(row => row.opaqueId === added.accountId) ? added : null;
    return boundedAccounts({ mode: 'managed', ...state, added: receipt });
  };
  const enqueue = operation => {
    mutations++;
    const task = mutationTail.then(() => { if (stopped) throw unavailable(); return operation(); });
    mutationTail = task.catch(() => {}).finally(() => { mutations--; });
    return task;
  };
  const serial = () => { if (next >= Number.MAX_SAFE_INTEGER) throw new Error('Codex unavailable'); return ++next; };
  const target = () => {
    const llm = get(ctx, 'llm');
    const settings = get(ctx, 'settings');
    if (!llm || !settings) return null;
    const rows = llm.listConfigurableProviders().filter(row => row.provider === PROVIDER);
    if (rows.length !== 1 || !validPath(rows[0].settingsPath)) return null;
    const descriptor = settings.describe({ redactSecrets: true }).find(row => row.ns === rows[0].settingsNs);
    if (!descriptor || !Number.isSafeInteger(descriptor.revision) || descriptor.revision < 0) return null;
    return { llm, settings, row: rows[0], descriptor };
  };
  const runtimeTarget = () => {
    const route = target();
    if (!route || !validCodexRuntimeRevision(route.descriptor.revision)) throw runtimeUnavailable();
    return { ...route, row: Object.freeze({ settingsNs: route.row.settingsNs, settingsPath: Object.freeze(['providers', PROVIDER]) }) };
  };
  const runtimeSnapshot = route => {
    const profile = at(route.descriptor.value, route.row.settingsPath);
    if (profile !== undefined && !object(route.descriptor.user)) throw runtimeUnavailable();
    const result = {
      version: 1, revision: route.descriptor.revision,
      configured: profile !== undefined,
      writable: profile !== undefined && route.settings.writable === true && !retryBlocked && route.descriptor.revision < Number.MAX_SAFE_INTEGER,
      values: projectCodexRuntimeValues(profile),
      overrides: projectCodexRuntimeValues(at(route.descriptor.user, route.row.settingsPath)),
      baseValues: projectCodexRuntimeBaseValues(route.descriptor.schema, at(route.descriptor.base, route.row.settingsPath)),
    };
    if (Buffer.byteLength(JSON.stringify(result)) > 4096) throw runtimeUnavailable();
    return Object.freeze(result);
  };
  const sameRuntimeTarget = (left, right) => sameService(left.llm, right.llm)
    && sameService(left.settings, right.settings) && left.row.settingsNs === right.row.settingsNs;
  const runtimeSave = async command => {
    // Capture process input before joining the account/configuration mutation lane.
    const values = validateCodexRuntimeValues(command.values);
    const expectedRevision = command.expectedRevision;
    if (!validCodexRuntimeRevision(expectedRevision) || stopped || active?.running || mutations > 0 || retryBlocked) throw runtimeUnavailable();
    let invoked = false;
    try {
      const admitted = runtimeTarget();
      return await enqueue(async () => {
        const route = runtimeTarget();
        if (stopped || active?.running || retryBlocked || !sameRuntimeTarget(admitted, route)) throw runtimeUnavailable();
        const before = runtimeSnapshot(route);
        if (!before.configured || !before.writable) throw runtimeUnavailable();
        if (before.revision !== expectedRevision) throw runtimeUnavailable('CODEX_RUNTIME_CONFLICT');
        invoked = true;
        try {
          await route.settings.mutate(route.row.settingsNs, codexRuntimePathOps(values), before.revision);
        } catch (error) {
          throw runtimeUnavailable(error?.code === 'SETTINGS_CONFLICT' ? 'CODEX_RUNTIME_CONFLICT' : 'CODEX_RUNTIME_INDETERMINATE');
        }
        const current = runtimeTarget();
        const after = runtimeSnapshot(current);
        if (stopped || !sameRuntimeTarget(route, current) || !after.configured || after.revision < before.revision
            || after.revision > before.revision + 1) throw runtimeUnavailable('CODEX_RUNTIME_INDETERMINATE');
        // Public Settings revisions change on value/owner change, not every no-op.
        for (const field of Object.keys(values)) {
          if (after.baseValues[field] !== before.baseValues[field]
              || after.values[field] !== (values[field] === null ? after.baseValues[field] : values[field])) throw runtimeUnavailable('CODEX_RUNTIME_INDETERMINATE');
        }
        return after;
      });
    } catch (error) {
      if (['CODEX_RUNTIME_CONFLICT', 'CODEX_RUNTIME_INDETERMINATE'].includes(error?.code)) throw error;
      throw runtimeUnavailable(invoked ? 'CODEX_RUNTIME_INDETERMINATE' : 'CODEX_RUNTIME_UNAVAILABLE');
    }
  };
  const snapshot = async () => {
    for (let retry = 0; retry < 8; retry++) {
      const captured = version;
      const owner = managed();
      let available, configured;
      if (owner) {
        const accounts = await readAccounts(owner);
        available = true;
        configured = accounts.selected !== null;
      } else {
        const flow = get(ctx, 'authorization')?.describe(KEY);
        const credentials = get(ctx, 'credentials');
        const record = credentials ? await credentials.describeRecord(KEY) : undefined;
        available = !!flow?.methods?.some(method => method.id === 'oauth');
        configured = record?.configured === true && record.kind === 'grant';
      }
      if (stopped) throw unavailable();
      if (captured !== version) continue;
      const route = target();
      const value = { available, credentialStored: configured,
        routeConfigured: !!route?.llm.listProviders().some(row => row.id === PROVIDER), phase,
        attempt: active?.id ?? null, prompt: active?.prompt?.id ?? null, browserAvailable: !!active?.url,
        settingsRevision: route?.descriptor.revision ?? null, retryBlocked };
      return { value, browserUrl: active?.url ?? null, version: captured };
    }
    throw new Error('Codex unavailable');
  };
  const metadata = async () => {
    for (let retry = 0; retry < 8; retry++) {
      const state = await snapshot();
      if (!stopped && state.version === version) return state.value;
    }
    throw new Error('Codex unavailable');
  };
  const publish = async () => {
    try { const state = await snapshot(); if (!stopped && state.version === version) emit({ type: 'codex-state', value: state.value, browserUrl: state.browserUrl }); }
    catch (_error) { /* Private metadata refresh failures never expose provider errors. */ }
  };
  const retirePrompt = attempt => {
    const pending = attempt.prompt;
    attempt.prompt = null;
    attempt.url = null;
    version++;
    if (pending) { pending.cleanup(); pending.reject(new Error('Codex response withdrawn')); }
  };
  const cancel = attempt => {
    if (!attempt || active !== attempt) return;
    retryBlocked = true;
    phase = 'indeterminate';
    attempt.url = null;
    retirePrompt(attempt);
    attempt.controller.abort();
    if (attempt.owner) {
      const task = Promise.resolve().then(() => {
        const current = get(ctx, 'codexAccounts');
        // Replacement/loss cannot redirect cancellation away from the captured login owner.
        return (sameService(current, attempt.owner) ? current : attempt.owner).cancelLogin();
      });
      cancelTasks.add(task);
      void task.catch(() => { /* Cancellation uncertainty remains sticky. */ }).finally(() => cancelTasks.delete(task));
    } else get(ctx, 'authorization')?.cancel(KEY);
    void publish();
  };
  const start = async (command = null) => {
    const owner = managed();
    if (owner) {
      const state = await readAccounts(owner);
      command ??= { label: 'ChatGPT account', expectedEpoch: state.epoch };
      if (!validCodexLabel(command.label) || !validEpoch(command.expectedEpoch)) throw unavailable();
      if (state.epoch !== command.expectedEpoch) throw conflict();
    } else if (command) throw unavailable();
    if (stopped || retryBlocked || active?.running) throw new Error('Codex unavailable');
    const before = await metadata();
    if (stopped || retryBlocked || active?.running || !before.available) throw new Error('Codex unavailable');
    const attempt = { id: serial(), owner, controller: new AbortController(), prompt: null, url: null, running: true, timer: null, task: null };
    added = null;
    active = attempt;
    phase = 'waiting-browser';
    version++;
    const prompt = question => {
      if (stopped || active !== attempt || attempt.controller.signal.aborted || question.signal?.aborted) return Promise.reject(new Error('Codex response withdrawn'));
      if (question.kind === 'select') {
        const ids = question.options?.map(option => option.id);
        if (!Array.isArray(ids) || ids.length !== 2 || ids[0] !== 'browser' || ids[1] !== 'device_code') return Promise.reject(new Error('Unsupported Codex prompt'));
        return Promise.resolve('browser');
      }
      if (!['text', 'secret'].includes(question.kind) || attempt.prompt
          || question.message !== 'Complete login in your browser, or paste the authorization code / redirect URL here:'
          || question.placeholder !== 'http://localhost:1455/auth/callback') return Promise.reject(new Error('Unsupported Codex prompt'));
      return new Promise((resolve, reject) => {
        const onAbort = () => { if (attempt.prompt?.id === id) retirePrompt(attempt); void publish(); };
        const id = serial();
        const cleanup = () => { question.signal?.removeEventListener('abort', onAbort); attempt.controller.signal.removeEventListener('abort', onAbort); };
        attempt.prompt = { id, resolve, reject, cleanup };
        version++;
        question.signal?.addEventListener('abort', onAbort, { once: true });
        attempt.controller.signal.addEventListener('abort', onAbort, { once: true });
        void publish();
      });
    };
    attempt.timer = setTimeout(() => cancel(attempt), timeoutMs);
    const interaction = { prompt, notify: notice => {
        if (stopped || active !== attempt || attempt.controller.signal.aborted) return;
        if (notice.url !== undefined) {
          if (!validCodexUrl(notice.url)) { cancel(attempt); return; }
          addSecret(notice.url);
          attempt.url = notice.url;
          version++;
          void publish();
        }
      } };
    // Login owns the mutation lane through settlement; cancel/callback never wait on that lane.
    attempt.task = enqueue(async () => {
      if (attempt.controller.signal.aborted) throw unavailable();
      if (owner) {
        currentOwner(owner);
        const state = await readAccounts(owner);
        if (state.epoch !== command.expectedEpoch) throw conflict();
        const receipt = await currentOwner(owner).beginLogin({ label: command.label, expectedEpoch: command.expectedEpoch, signal: attempt.controller.signal, interaction });
        if (!exact(receipt, ['account', 'epoch']) || !validEpoch(receipt.epoch)) throw unavailable();
        const account = accountMetadata(receipt.account);
        if (receipt.epoch < command.expectedEpoch || account.label !== command.label || state.accounts.some(row => row.opaqueId === account.opaqueId)) throw unavailable();
        if (stopped || active !== attempt || attempt.controller.signal.aborted || retryBlocked) return;
        currentOwner(owner);
        added = { accountId: account.opaqueId, epoch: receipt.epoch, attempt: attempt.id };
        phase = 'authorized';
      } else {
        const outcome = await get(ctx, 'authorization').begin({ key: KEY, method: 'oauth', signal: attempt.controller.signal, interaction });
        if (active !== attempt) return;
        if (retryBlocked) phase = 'indeterminate';
        else if (outcome.status === 'authorized') phase = 'authorized';
        else { retryBlocked = true; phase = 'cancelled'; }
      }
      attempt.url = null;
      version++;
    }).then(() => {}, _error => {
      if (active !== attempt) return;
      attempt.url = null;
      version++;
      retryBlocked = true; phase = attempt.controller.signal.aborted ? 'indeterminate' : 'failed';
    }).finally(() => {
      clearTimeout(attempt.timer);
      attempt.running = false;
      attempt.url = null;
      retirePrompt(attempt);
      void publish();
    });
    return metadata();
  };
  return {
    get busy() { return active?.running === true || mutations > 0 || retryBlocked; },
    async handle(command) {
      if (stopped) throw ['codex-runtime-read', 'codex-runtime-save'].includes(command.type) ? runtimeUnavailable() : unavailable();
      switch (command.type) {
        case 'codex-runtime-read': {
          try {
            if (active?.running || mutations > 0) throw runtimeUnavailable();
            return runtimeSnapshot(runtimeTarget());
          } catch (_error) { throw runtimeUnavailable(); }
        }
        case 'codex-runtime-save': return runtimeSave(command);
        case 'codex-status': return metadata();
        case 'codex-accounts-status': { const state = await accountsStatus(true); void publish(); return state; }
        case 'codex-start': return start();
        case 'codex-add': return start(command);
        case 'codex-select': case 'codex-signout': case 'codex-signout-all':
          return enqueue(async () => {
            const owner = managed();
            if (!owner || active?.running || retryBlocked || !validEpoch(command.expectedEpoch)) throw unavailable();
            const state = await readAccounts(owner);
            if (state.epoch !== command.expectedEpoch) throw conflict();
            if (command.type !== 'codex-signout-all' && (!validCodexAccountId(command.accountId) || !state.accounts.some(row => row.opaqueId === command.accountId))) throw unavailable();
            try {
              if (command.type === 'codex-select') await currentOwner(owner).select(command.accountId, command.expectedEpoch);
              else if (command.type === 'codex-signout') await currentOwner(owner).signOut(command.accountId, command.expectedEpoch);
              else await currentOwner(owner).signOutAll(command.expectedEpoch);
              version++;
              currentOwner(owner);
              const result = await accountsStatus();
              if (command.type === 'codex-select' && result.selected !== command.accountId || command.type === 'codex-signout' && result.accounts.some(row => row.opaqueId === command.accountId) || command.type === 'codex-signout-all' && result.accounts.length !== 0) throw unavailable();
              void publish();
              return result;
            } catch (error) {
              if (error?.code !== 'CODEX_EPOCH_CONFLICT') { retryBlocked = true; phase = 'indeterminate'; added = null; version++; void publish(); }
              throw error?.code === 'CODEX_EPOCH_CONFLICT' ? conflict() : unavailable();
            }
          });
        case 'codex-cancel':
          if (!safeId(command.attempt) || active?.id !== command.attempt) throw new Error('Codex unavailable');
          if (active.running) cancel(active); return metadata();
        case 'codex-callback': {
          const pending = active?.prompt;
          if (!safeId(command.attempt) || !safeId(command.prompt) || active?.id !== command.attempt || pending?.id !== command.prompt || !active.running || active.controller.signal.aborted) return { ok: false };
          addSecret(command.response);
          active.prompt = null;
          active.url = null;
          version++;
          pending.cleanup(); pending.resolve(command.response);
          void publish();
          return { ok: true };
        }
        case 'codex-enable-models': {
          if (active?.running || mutations > 0 || retryBlocked) throw unavailable();
          const expectedRevision = command.expectedRevision;
          return enqueue(async () => {
            const route = target();
            const status = await metadata();
            if (stopped || !route || active?.running || retryBlocked || !status.credentialStored || !Number.isSafeInteger(expectedRevision) || expectedRevision !== route.descriptor.revision || route.settings.writable !== true) throw unavailable();
            if (at(route.descriptor.value, route.row.settingsPath) === undefined) {
              await route.settings.mutate(route.row.settingsNs, [{ op: 'set', path: route.row.settingsPath, value: {} }], expectedRevision);
            }
            if (!route.llm.listProviders().some(row => row.id === PROVIDER)) throw unavailable();
            return metadata();
          });
        }
        default: throw new Error('Codex unavailable');
      }
    },
    async stop() {
      if (stopTask) return stopTask;
      stopped = true;
      if (active?.running) cancel(active);
      return stopTask = (async () => {
        if (active) { active.url = null; retirePrompt(active); clearTimeout(active.timer); await active.task; }
        await mutationTail;
        await Promise.allSettled([...cancelTasks]);
      })();
    },
  };
}
